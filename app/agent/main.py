# Singleton Agent holder with lazy-loading support
_agent_instance: Optional[Agent] = None


def get_agent() -> Agent:
    """
    Returns the initialized Agent instance.
    Uses lazy initialization so the service starts cleanly and retries
    if dependencies (like Qdrant or embedding models) become available.
    """
    global _agent_instance
    if _agent_instance is None:
        try:
            logger.info("Initializing Agent instance...")
            _agent_instance = Agent()
            logger.info("Agent instance initialized successfully.")
        except Exception as e:
            logger.exception("Failed to initialize Agent instance: %s", e)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Agent initialization failed: {str(e)}"
            )
    return _agent_instance


@app.on_event("startup")
def startup_event():
    """
    Attempt pre-initialization on startup. If an external lock exists
    (e.g., another process holding local Qdrant storage), log a warning
    and allow lazy-loading on request.
    """
    global _agent_instance
    try:
        _agent_instance = Agent()
        logger.info("Agent pre-initialized on startup.")
    except Exception as e:
        logger.warning(
            "Agent could not be pre-initialized at startup (will retry on request): %s", e
        )


