@app.post(
    "/v1/chat",
    response_model=ChatResponse,
    summary="Agent Chat and Reasoning Endpoint",
    tags=["Agent"]
)
def chat(req: ChatRequest):
    """
    Process a question through the Agent reasoning loop:
    1. Validates the question.
    2. Retrieves or initializes the existing Agent class.
    3. Streams execution via agent.run_stream(question).
    4. Collects tokens, logs, and done results.
    5. Returns a structured JSON response.
    """
    # 1. Validate the question
    cleaned_question = req.question.strip() if req.question else ""
    if not cleaned_question:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The 'question' field cannot be empty or contain only whitespace."
        )

    # 2. Get existing Agent instance
    agent = get_agent()

    # 3. Execution tracking state
    collected_tokens: List[str] = []
    collected_steps: List[str] = []
    sources: List[Any] = []
    intent: str = "unknown"
    final_answer: str = ""
    status_str: str = "completed"

    # 4. Stream and collect events
    try:
        logger.info("Executing Agent for query: %s", cleaned_question[:100])

        for event in agent.run_stream(cleaned_question):
            event_type = event.get("type")

            if event_type == "step":
                msg = event.get("message")
                if msg:
                    collected_steps.append(msg)

            elif event_type == "classification":
                intent = event.get("intent", intent)

            elif event_type == "token":
                token_text = event.get("content", "")
                collected_tokens.append(token_text)

            elif event_type == "retrieval":
                retrieved_sources = event.get("sources", [])
                if retrieved_sources:
                    sources = retrieved_sources

            elif event_type == "done":
                result = event.get("result", {})
                final_answer = result.get("answer", "")
                if result.get("sources"):
                    sources = result.get("sources", [])
                if result.get("steps"):
                    collected_steps = result.get("steps", collected_steps)
                if result.get("intent"):
                    intent = result.get("intent", intent)
                if result.get("status"):
                    status_str = result.get("status", status_str)

        # Fallback to token concatenation if done event did not contain answer
        if not final_answer and collected_tokens:
            final_answer = "".join(collected_tokens)

        return {
            "answer": final_answer,
            "steps": collected_steps,
            "sources": sources,
            "intent": intent,
            "status": status_str,
        }

    except HTTPException:
        raise
    except Exception as e:
        logger.exception("Agent execution encountered an unhandled error")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Agent execution failed: {str(e)}"
        )


