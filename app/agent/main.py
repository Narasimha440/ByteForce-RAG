# REQUEST & RESPONSE MODELS
# ---------------------------------------------------------------------------
class ChatRequest(BaseModel):
    """
    Request model for the Agent chat endpoint.
    Primary field is `question`. Optional fields provide future readiness
    for Vision, OCR, and multimodal document workflows without breaking changes.
    """
    question: str = Field(
        ...,
        description="The user's query or instruction for the Agent."
    )
    image_base64: Optional[str] = Field(
        default=None,
        description="Reserved for future vision analysis."
    )
    file_path: Optional[str] = Field(
        default=None,
        description="Reserved for future document inspection/OCR."
    )

    class Config:
        json_schema_extra = {
            "example": {
                "question": "What is the maintenance procedure?"
            }
        }


class ChatResponse(BaseModel):
    """
    Response model returning the Agent's answer and execution metadata.
    """
    answer: str = Field(..., description="The final synthesized answer generated by the agent.")
    steps: List[str] = Field(default_factory=list, description="Execution steps performed during reasoning.")
    sources: List[Any] = Field(default_factory=list, description="Retrieved evidence sources if RAG was used.")
    intent: str = Field(default="unknown", description="The classified user intent.")
    status: str = Field(default="completed", description="Execution status (e.g., completed, failed).")


class HealthResponse(BaseModel):
    status: str
    service: str


